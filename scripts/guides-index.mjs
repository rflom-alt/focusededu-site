#!/usr/bin/env node
// Writes src/lib/guides/index.ts from src/lib/guides/manifest.json.
// The manifest is the list of leadership guides on this site: add a guide by adding its JSON
// beside the manifest and one entry in it, then run `node scripts/guides-index.mjs`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "guides");
const manifest = JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8"));
const name = (slug) => "g_" + slug.replace(/[^a-z0-9]+/gi, "_");

for (const g of manifest.guides) {
  if (!fs.existsSync(path.join(dir, g.slug + ".json"))) throw new Error(`manifest names ${g.slug} but ${g.slug}.json is missing`);
}

const out = `// GENERATED by scripts/guides-index.mjs from manifest.json. Do not edit by hand:
// change manifest.json (or a guide's JSON) and run \`node scripts/guides-index.mjs\`.
import type { Guide, GuideData, HubLink } from "@/lib/guides/types";
import manifest from "./manifest.json";
${manifest.guides.map((g) => `import ${name(g.slug)} from "./${g.slug}.json";`).join("\n")}

const data: Record<string, GuideData> = {
${manifest.guides.map((g) => `  ${JSON.stringify(g.slug)}: ${name(g.slug)} as GuideData,`).join("\n")}
};

// The leadership guides on this site. The page, the hub, the sitemap and the llms files all read this list.
export const guides: Guide[] = manifest.guides.map(({ slug, ...rest }) => ({ data: data[slug], ...rest }));

export const getGuide = (slug: string) => guides.find((g) => g.data.slug === slug);

// The hub: these guides, plus pages elsewhere on the site rebuilt to the same standard, in the manifest's order.
export const leadershipLinks: HubLink[] = manifest.hub.map((h: string | HubLink) => {
  if (typeof h !== "string") return h;
  const g = guides.find((x) => x.data.slug === h)!;
  return { title: g.card.title, body: g.card.body, href: \`/resources/\${h}\` };
});

export type { GuideData };
`;
fs.writeFileSync(path.join(dir, "index.ts"), out);
console.log(`index.ts: ${manifest.guides.length} guides, ${manifest.hub.length} hub cards`);
